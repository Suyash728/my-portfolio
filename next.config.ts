import type { NextConfig } from "next";

/**
 * The page loads no third-party script, frame or image, so the headers below
 * cost nothing and close the defaults that browsers leave open. A full CSP is
 * the next step up and needs nonces for the JSON-LD block and Next's own
 * bootstrap script, which is why it isn't here yet.
 */
const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "X-Frame-Options", value: "DENY" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(), interest-cohort=()",
  },
];

const nextConfig: NextConfig = {
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
  /**
   * The mark is generated by `src/app/icon.tsx`, so there is no favicon.ico to
   * serve. Modern clients follow the <link rel="icon"> tag, but enough tooling
   * still asks for /favicon.ico by hand that a 404 there is not worth it.
   */
  async rewrites() {
    return [{ source: "/favicon.ico", destination: "/icon" }];
  },
};

export default nextConfig;
