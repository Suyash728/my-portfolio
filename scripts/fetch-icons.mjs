/**
 * Regenerates src/content/icons.generated.ts from Simple Icons.
 *
 * Run with:  node scripts/fetch-icons.mjs
 *
 * Icon paths are vendored rather than loaded from a CDN at runtime: the page
 * ships one request, works offline, and nothing external can change what the
 * site renders. Re-run this only when a slug is added to SLUGS below.
 */
import { writeFileSync } from "node:fs";

const VERSION = "13";
const BASE = `https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}`;

const SLUGS = [
  "python", "javascript", "typescript", "openjdk", "cplusplus",
  "postgresql", "mysql", "nextdotjs", "react", "tailwindcss",
  "fastapi", "nodedotjs", "supabase", "firebase", "googlebigquery",
  "googlecloud", "vercel", "cloudflare", "railway", "git",
  "github", "linux", "polygon", "langchain", "googlegemini",
  "n8n", "arduino", "espressif", "solidity", "huggingface",
];

const meta = await fetch(`${BASE}/_data/simple-icons.json`).then((r) => r.json());
const all = Array.isArray(meta) ? meta : meta.icons;

const slugify = (title) =>
  title
    .toLowerCase()
    .replace(/\+/g, "plus")
    .replace(/\./g, "dot")
    .replace(/&/g, "and")
    .normalize("NFKD")
    .replace(/[^a-z0-9]/g, "");

const hexBySlug = new Map(all.map((i) => [i.slug ?? slugify(i.title), i.hex]));

/**
 * Brand colours are picked for a white page, and several of them (JavaScript's
 * yellow, Linux's amber) all but vanish on our warm ground. `safe` is the brand
 * colour walked darker until it clears 3:1 against that ground, so the marks
 * read as coloured without any of them going washed out. Most brands are
 * already dark enough and come back unchanged.
 */
const PAGE_GROUND = [0xf2, 0xef, 0xe9];
const MIN_CONTRAST = 3;

const channel = (c) => {
  const s = c / 255;
  return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};

const luminance = ([r, g, b]) =>
  0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);

const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const toHex = (rgb) =>
  rgb.map((c) => Math.round(c).toString(16).padStart(2, "0")).join("");

function darkenToLegible(hex) {
  let rgb = [
    parseInt(hex.slice(0, 2), 16),
    parseInt(hex.slice(2, 4), 16),
    parseInt(hex.slice(4, 6), 16),
  ];
  // Walk down in small steps so the hue survives; 60 steps at 0.94 is ample.
  for (let i = 0; i < 60 && contrast(rgb, PAGE_GROUND) < MIN_CONTRAST; i++) {
    rgb = rgb.map((c) => c * 0.94);
  }
  return toHex(rgb).toUpperCase();
}

const entries = [];
for (const slug of SLUGS) {
  const svg = await fetch(`${BASE}/icons/${slug}.svg`).then((r) =>
    r.ok ? r.text() : null,
  );
  const path = svg?.match(/ d="([^"]+)"/)?.[1];
  const hex = hexBySlug.get(slug);
  if (!path || !hex) {
    console.warn(`skipped ${slug} (path: ${!!path}, hex: ${!!hex})`);
    continue;
  }
  entries.push({ slug, path, hex, safe: darkenToLegible(hex) });
}

const adjusted = entries.filter((e) => e.safe !== e.hex.toUpperCase());
console.log(
  `darkened for legibility: ${
    adjusted.map((e) => `${e.slug} #${e.hex}→#${e.safe}`).join(", ") || "none"
  }`,
);

const body = entries
  .map(
    (e) =>
      `  ${e.slug}: { hex: "#${e.safe}", brand: "#${e.hex}", path: "${e.path}" },`,
  )
  .join("\n");

writeFileSync(
  new URL("../src/content/icons.generated.ts", import.meta.url),
  `// Generated by scripts/fetch-icons.mjs from simple-icons@${VERSION}. Do not edit by hand.
// Marks are the trademarks of their respective owners, used here to identify the technology.

export interface BrandIcon {
  /** Brand colour as rendered — darkened where the true brand colour would
   *  fall below 3:1 on the page ground. This is the one to paint with. */
  readonly hex: string;
  /** The untouched official brand colour, for reference. */
  readonly brand: string;
  /** Single path, 24x24 viewBox. */
  readonly path: string;
}

export const ICONS = {
${body}
} as const satisfies Record<string, BrandIcon>;

export type IconSlug = keyof typeof ICONS;
`,
  "utf8",
);

console.log(`wrote ${entries.length} icons`);
